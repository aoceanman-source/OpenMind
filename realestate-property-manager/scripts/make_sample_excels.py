from pathlib import Path

from openpyxl import Workbook

OUT = Path(__file__).resolve().parent / "sample_legacy"
OUT.mkdir(exist_ok=True)

RENT_HEADER = ["樓層", "區劃", "面積(坪)", "現況", "租客", "業種",
               "月租金", "共益費", "想定月租", "押金", "契約開始", "契約結束"]


def make(filename, overview, rent_rows):
    wb = Workbook()
    ws1 = wb.active
    ws1.title = "物件概要"
    for label, value in overview:
        ws1.append([label, value])
    ws1.column_dimensions["A"].width = 16
    ws1.column_dimensions["B"].width = 40

    ws2 = wb.create_sheet("レントロール")
    ws2.append(RENT_HEADER)
    for r in rent_rows:
        ws2.append(r)
    for col in "ABCDEFGHIJKL":
        ws2.column_dimensions[col].width = 14

    path = OUT / filename
    wb.save(path)
    print(f"  ✓ 產生 {path}")


